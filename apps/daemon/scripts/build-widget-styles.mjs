import { spawnSync } from "node:child_process";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const daemonRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const dataDir = join(daemonRoot, ".data");
const compiledPath = join(dataDir, "widget.css");
await mkdir(dataDir, { recursive: true });
const result = spawnSync("pnpm", [
  "exec",
  "tailwindcss",
  "-i",
  "src/widget.css",
  "-o",
  compiledPath,
  "--minify",
], {
  cwd: daemonRoot,
  encoding: "utf8",
});

if (result.status !== 0) {
  process.stderr.write(result.stderr || result.stdout || "Tailwind CSS build failed.\n");
  process.exit(result.status ?? 1);
}

const css = await readFile(compiledPath, "utf8");
await writeFile(
  join(daemonRoot, "src/widget-styles.ts"),
  `// Generated by scripts/build-widget-styles.mjs. Do not edit directly.\nexport const WIDGET_STYLES = ${JSON.stringify(css)};\n`,
);
